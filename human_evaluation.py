#!/usr/bin/env python3
"""
Human Evaluation Script
Evaluates AraELECTRA 9feat v4 and AraBERT 9feat v4
on 14 unseen texts (7 Human + 7 AI-generated by GPT-4o)
"""

import pandas as pd
import numpy as np
import torch
import joblib
import warnings
warnings.filterwarnings("ignore")

from pathlib import Path
from scipy.special import softmax
from transformers import AutoConfig
from sklearn.metrics import (
    accuracy_score, f1_score, precision_score, recall_score,
    confusion_matrix, matthews_corrcoef, classification_report
)

from src import processing, feature_engineering, model

# ── Model configurations ──────────────────────────────────────
MODELS = {
    "AraELECTRA 9feat v4": {
        "model_dir":   "models/SOTA_model_AraELECTRA_9_features_OriginalData_Tuned_v4/final_model_with_features",
        "scaler_path": "models/SOTA_model_AraELECTRA_9_features_OriginalData_Tuned_v4/scaler_SOTA_AraELECTRA_9_features_v4.joblib",
    },
    "AraBERT 9feat v4": {
        "model_dir":   "models/SOTA_model_AraBERT_9_features_OriginalData_Tuned_v4/final_model_with_features",
        "scaler_path": "models/SOTA_model_AraBERT_9_features_OriginalData_Tuned_v4/scaler_SOTA_AraBERT_9_features_v4.joblib",
    },
}

FEAT_COLS = [
    "word_count","sentence_count","avg_sentence_length","sentence_length_std",
    "perplexity","stop_word_ratio","repetition_score_3gram","hapax_ratio","mtld"
]

DEVICE = torch.device("cpu")


def load_model(model_dir):
    model_path = Path(model_dir).resolve()
    config = AutoConfig.from_pretrained(str(model_path), local_files_only=True)
    config._attn_implementation = "eager"
    loaded_model = model.AdvancedHybridModel(config)

    best_pt = model_path / "best_model_state_dict.pt"
    if best_pt.exists():
        raw = torch.load(str(best_pt), map_location=DEVICE)
        new = {}
        for k, v in raw.items():
            if k.startswith("electra."): new[k.replace("electra.", "transformer.", 1)] = v
            elif k.startswith("bert."):   new[k.replace("bert.", "transformer.", 1)] = v
            else: new[k] = v
        missing, unexpected = loaded_model.load_state_dict(new, strict=False)
        print(f"  Weights loaded: Missing={len(missing)}, Unexpected={len(unexpected)}")
    else:
        from safetensors.torch import load_file
        weights = load_file(str(model_path / "model.safetensors"))
        missing, unexpected = loaded_model.load_state_dict(weights, strict=False)
        print(f"  Weights loaded: Missing={len(missing)}, Unexpected={len(unexpected)}")

    loaded_model.to(DEVICE)
    loaded_model.eval()
    tokenizer = processing.get_tokenizer(str(model_path))
    return loaded_model, tokenizer


def run_inference(loaded_model, tokenizer, scaler, texts, features_array):
    features_scaled = scaler.transform(
        pd.DataFrame(features_array, columns=FEAT_COLS))

    all_preds, all_scores = [], []
    with torch.no_grad():
        for start in range(0, len(texts), 8):
            end = min(start + 8, len(texts))
            inputs = tokenizer(
                texts[start:end], padding="max_length", truncation=True,
                max_length=256, return_tensors="pt").to(DEVICE)
            feat_tensor = torch.tensor(
                features_scaled[start:end], dtype=torch.float).to(DEVICE)
            outputs = loaded_model(
                input_ids=inputs["input_ids"],
                attention_mask=inputs["attention_mask"],
                token_type_ids=inputs.get("token_type_ids"),
                explicit_features=feat_tensor)
            logits = outputs.logits.cpu().numpy()
            probs  = softmax(logits, axis=1)
            all_preds.extend(np.argmax(logits, axis=1).tolist())
            all_scores.extend(probs[:, 1].tolist())

    return np.array(all_preds), np.array(all_scores)


def print_results(model_name, y_true, y_pred, y_score, df):
    acc_n = accuracy_score(y_true, y_pred)
    acc_f = accuracy_score(y_true, 1 - y_pred)
    if acc_f > acc_n:
        print("  Applying label flip...")
        y_pred  = 1 - y_pred
        y_score = 1 - y_score

    cm = confusion_matrix(y_true, y_pred, labels=[0,1])
    tn, fp, fn, tp = cm.ravel()
    acc  = accuracy_score(y_true, y_pred)
    f1   = f1_score(y_true, y_pred, zero_division=0)
    prec = precision_score(y_true, y_pred, zero_division=0)
    rec  = recall_score(y_true, y_pred, zero_division=0)
    spec = tn/(tn+fp) if (tn+fp)>0 else 0
    mcc  = matthews_corrcoef(y_true, y_pred)

    SEP = "="*55
    print(f"\n{SEP}")
    print(f"  {model_name}")
    print(f"  Human Evaluation — 14 Unseen Texts")
    print(SEP)
    print(f"  Accuracy    : {acc*100:.2f}%")
    print(f"  F1-Score    : {f1*100:.2f}%")
    print(f"  Precision   : {prec*100:.2f}%")
    print(f"  Recall      : {rec*100:.2f}%")
    print(f"  Specificity : {spec*100:.2f}%")
    print(f"  MCC         : {mcc:.4f}")
    print(f"  TP={tp}  TN={tn}  FP={fp}  FN={fn}")
    print(SEP)

    print("\nPer-sample predictions:")
    print(f"{'ID':<15} {'True':>6} {'Pred':>6} {'Score':>7} {'Correct':>8}")
    print("-"*45)
    for i, row in df.iterrows():
        true = y_true[i]
        pred = y_pred[i]
        score = y_score[i]
        correct = "YES" if true==pred else "NO"
        label_true = "Human" if true==0 else "AI"
        label_pred = "Human" if pred==0 else "AI"
        print(f"{str(row['id']):<15} {label_true:>6} {label_pred:>6} {score:>7.4f} {correct:>8}")

    return {
        "Model": model_name,
        "Accuracy": round(acc,4), "F1": round(f1,4),
        "Precision": round(prec,4), "Recall": round(rec,4),
        "Specificity": round(spec,4), "MCC": round(mcc,4),
        "TP": int(tp), "TN": int(tn), "FP": int(fp), "FN": int(fn),
        "y_pred": y_pred.tolist(), "y_score": [round(s,4) for s in y_score.tolist()]
    }


def main():
    print("="*55)
    print("  Human Evaluation - Arabic AI Text Detection")
    print("  AraELECTRA 9feat v4 vs AraBERT 9feat v4")
    print("="*55)

    df = pd.read_csv("human_eval_texts.csv", encoding="utf-8-sig")
    df = df.reset_index(drop=True)
    print(f"\nLoaded {len(df)} texts")
    print(f"Human: {len(df[df['true_label']==0])} | AI: {len(df[df['true_label']==1])}")

    print("\nPreprocessing texts...")
    df["text_processed"] = df["text"].astype(str).apply(
        processing.light_preprocess_for_llm)
    texts  = df["text_processed"].tolist()
    y_true = df["true_label"].values

    print("Calculating linguistic features...")
    feature_engineering.initialize_feature_engineering()
    feat_dicts = [feature_engineering.calculate_features(t) for t in texts]
    feat_df    = pd.DataFrame(feat_dicts)
    features_array = feat_df[FEAT_COLS].values.astype(float)
    print("Features calculated")

    all_results = []
    result_df   = df.copy()

    for model_name, cfg in MODELS.items():
        print(f"\n{'-'*55}")
        print(f"Loading {model_name}...")
        loaded_model, tokenizer = load_model(cfg["model_dir"])
        scaler = joblib.load(cfg["scaler_path"])
        print(f"  Scaler expects {scaler.n_features_in_} features")

        y_pred, y_score = run_inference(
            loaded_model, tokenizer, scaler, texts, features_array)

        metrics = print_results(model_name, y_true, y_pred, y_score, df)
        all_results.append(metrics)

        key = model_name.replace(" ","_")
        result_df[f"{key}_pred"]  = metrics["y_pred"]
        result_df[f"{key}_score"] = metrics["y_score"]
        result_df[f"{key}_correct"] = [
            1 if p==t else 0 for p,t in zip(metrics["y_pred"], y_true)]

    if len(all_results) == 2:
        p1 = np.array(all_results[0]["y_pred"])
        p2 = np.array(all_results[1]["y_pred"])
        agree      = np.mean(p1 == p2)
        both_corr  = np.mean((p1==y_true) & (p2==y_true))
        both_wrong = np.mean((p1!=y_true) & (p2!=y_true))
        print(f"\n{'='*55}")
        print(f"  Model Agreement Analysis")
        print(f"{'='*55}")
        print(f"  Both models agree   : {agree*100:.1f}%")
        print(f"  Both correct        : {both_corr*100:.1f}%")
        print(f"  Both wrong          : {both_wrong*100:.1f}%")
        print(f"{'='*55}")

    result_df.drop(columns=["text_processed"], errors="ignore").to_csv(
        "human_eval_results.csv", index=False, encoding="utf-8-sig")
    print(f"\nResults saved to: human_eval_results.csv")
    print("Human evaluation complete!")


if __name__ == "__main__":
    main()